def update_articles_data():
    import os
    import pprint
    target_path = os.path.join(os.path.dirname(__file__), "articles_data.py")
    
    # Import ARTICLES from pipeline/articles_data.py
    import sys
    sys.path.insert(0, os.path.dirname(__file__))
    import articles_data
    articles = articles_data.ARTICLES
    
    updated_count = 0
    for art in articles:
        slug = art["slug"]
        if slug in NEW_DIALOGUES:
            art["dialogue"] = NEW_DIALOGUES[slug]
            updated_count += 1
            
    print(f"Updated dialogue for {updated_count} articles.")
    
    # Write back to pipeline/articles_data.py
    with open(target_path, "w", encoding="utf-8") as f:
        f.write("# -*- coding: utf-8 -*-\n\nARTICLES = ")
        pprint.pprint(articles, stream=f, indent=2, width=120)
    print(f"Saved {target_path} successfully!")

if __name__ == "__main__":
    update_articles_data()
